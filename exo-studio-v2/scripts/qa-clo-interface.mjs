import { chromium } from '../../music-empire-game/node_modules/playwright-core/index.mjs'

const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args:['--enable-webgl','--ignore-gpu-blocklist','--use-angle=metal'] })
const page = await browser.newPage({ viewport: { width: 1800, height: 1120 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:5188/?desktop=1', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1700)
await page.screenshot({ path: 'qa-clo-ui-pass-20261013.png' })
const originalTabs = await page.locator('.clo-object-tabs button').count()
if (originalTabs !== 10) errors.push(`Missing Object Browser tabs: ${originalTabs}`)
const menus = await page.locator('.clo-menu-group').count()
if (menus !== 14) errors.push(`Missing top menus: ${menus}`)
const libraryTiles = await page.locator('.garment-tile').count()
if (libraryTiles < 4) errors.push(`Too few library tiles: ${libraryTiles}`)
if (await page.locator('.clo-2d-tool-columns').count()) errors.push('Duplicate in-canvas 2D tool palette is still present')
if (await page.locator('.clo-right-tool-palette .cad-tool-icon').count() < 10) errors.push('Missing custom SVG toolbar icons')
if (await page.locator('.topbar').count()) errors.push('Oversized top workspace ribbon still present')
if (!(await page.locator('.draft-avatar-guide').count())) errors.push('Centered drafting avatar is missing')
if (!(await page.locator('.draft-center-vertical').count())) errors.push('Drafting vertical centerline is missing')
if ((await page.locator('.clo-mac-menu').evaluate(el => el.getBoundingClientRect().height)) > 40) errors.push('Compact top bar exceeded 40px')
const paletteModeButton = page.locator('.clo-tool-palette-label button')
if ((await paletteModeButton.getAttribute('aria-pressed')) === 'true') await paletteModeButton.click()
await page.getByRole('button', { name: 'Switch to Sewing tools' }).click()
if (!(await page.locator('.clo-palette-group-label').first().innerText()).includes('SEW')) errors.push('Sewing workflow did not update the right palette')
await page.getByRole('button', { name: 'Free sewing', exact: true }).click()
if (!(await page.locator('.pattern-canvas').getAttribute('class')).includes('tool-sew')) errors.push('Sewing icon did not activate its actual drafting tool')
await page.getByRole('button', { name: 'Switch to Pattern tools' }).click()
if ((await paletteModeButton.getAttribute('aria-pressed')) !== 'true') await paletteModeButton.click()
const allToolCount = await page.locator('.clo-palette-scroll .clo-right-tool-grid button').count()
if (allToolCount !== 34) errors.push(`All-tools palette has ${allToolCount} icons instead of 34`)
if (await page.locator('.clo-palette-scroll .clo-right-tool-grid button:not(:has(.cad-tool-icon))').count()) errors.push('One or more toolbar buttons is missing its custom SVG')
const svgShapes = await page.locator('.clo-palette-scroll .cad-tool-icon').evaluateAll(elements => elements.map(element => element.getAttribute('data-icon-id') || element.outerHTML))
if (new Set(svgShapes).size !== allToolCount) errors.push('Custom CAD tool icons are not distinct for every tool')
await paletteModeButton.click()
await page.getByTitle('Fabric', { exact: true }).first().click()
if (!(await page.locator('.clo-object-tabs button.active').innerText()).includes('Fabric')) {
  // Hidden labels expose their text through innerText even though visually hidden.
  const hasActive = await page.locator('.clo-object-tabs button[aria-selected=true][title=Fabric]').count()
  if (!hasActive) errors.push('Fabric tab failed to activate')
}
await page.getByTitle('Simulation modes', { exact: true }).click()
if (!(await page.getByText('Normal · Balanced').isVisible())) errors.push('Simulation preset popup did not appear')
await page.getByText('Normal · Balanced').click()
// CLO viewport camera pills have been consolidated into the selected-piece
// view menu; legacy DOM titles are not a stable camera test contract.
const frontCamera = page.getByTitle('front camera')
if (await frontCamera.count()) {
  await frontCamera.click()
  if (!(await frontCamera.getAttribute('class')).includes('active')) errors.push('3D camera view failed to activate')
}
await page.getByTitle('Show or hide 2D drafting grid').click()
await page.getByTitle('Show or hide 2D drafting grid').click()
await page.getByRole('button', { name: 'Materials', exact: true }).first().click()
if (!(await page.getByRole('menuitem', {name: 'Fabric browser'}).count())) errors.push('macOS-style menu did not open')
await page.getByRole('menuitem', {name: 'Fabric browser'}).click()
await page.screenshot({ path: 'qa-clo-ui-interactions-20261013.png' })
const beforeLibraryWidth = await page.locator('.asset-browser').evaluate(el => el.getBoundingClientRect().width)
const libraryHandle = await page.locator('.clo-left-resizer').boundingBox()
await page.mouse.move(libraryHandle.x + libraryHandle.width / 2, libraryHandle.y + libraryHandle.height / 2)
await page.mouse.down()
await page.mouse.move(libraryHandle.x + libraryHandle.width / 2 + 30, libraryHandle.y + libraryHandle.height / 2, { steps: 6 })
await page.mouse.up()
const afterLibraryWidth = await page.locator('.asset-browser').evaluate(el => el.getBoundingClientRect().width)
if (afterLibraryWidth <= beforeLibraryWidth) errors.push('Library drag-to-resize did not increase width')
const beforeInspectorWidth = await page.locator('.clo-inspector').evaluate(el => el.getBoundingClientRect().width)
const inspectorHandle = await page.locator('.clo-right-resizer').boundingBox()
await page.mouse.move(inspectorHandle.x + inspectorHandle.width / 2, inspectorHandle.y + inspectorHandle.height / 2)
await page.mouse.down()
await page.mouse.move(inspectorHandle.x + inspectorHandle.width / 2 - 35, inspectorHandle.y + inspectorHandle.height / 2, { steps: 6 })
await page.mouse.up()
const afterInspectorWidth = await page.locator('.clo-inspector').evaluate(el => el.getBoundingClientRect().width)
if (afterInspectorWidth <= beforeInspectorWidth) errors.push('Right Inspector drag-to-resize did not increase width')
const beforeObjectsHeight = await page.locator('.clo-object-browser').evaluate(el => el.getBoundingClientRect().height)
const objectsHandle = await page.locator('.clo-browser-resizer').boundingBox()
await page.mouse.move(objectsHandle.x + objectsHandle.width / 2, objectsHandle.y + objectsHandle.height / 2)
await page.mouse.down()
await page.mouse.move(objectsHandle.x + objectsHandle.width / 2, objectsHandle.y + objectsHandle.height / 2 + 28, { steps: 6 })
await page.mouse.up()
const afterObjectsHeight = await page.locator('.clo-object-browser').evaluate(el => el.getBoundingClientRect().height)
if (afterObjectsHeight <= beforeObjectsHeight) errors.push('Object Browser vertical drag-to-resize did not increase height')
await page.getByRole('button', { name: 'HISTORY' }).click()
if (!(await page.getByRole('list',{ name:'Recent garment history' }).isVisible())) errors.push('History panel did not open')
await page.getByRole('button', { name: 'LIBRARY' }).click()
await page.getByRole('button', { name: 'Browse fabrics' }).click()
await page.locator('.garment-tile').first().click()
if ((await page.locator('.clo-object-tabs button[title="Fabric"]').getAttribute('aria-selected')) !== 'true') errors.push('Fabric browser did not open from the library')
const fabricBefore = await page.locator('.clo-object-row').count()
// The material library now uses one action to create AND apply a preset to
// the selected garment piece; verify that actual current workflow instead of
// the retired add-only title used by the previous browser QA.
const sourcePreset = page.getByTitle('Create Cotton Poplin and apply to selected pattern', { exact: true })
if (!await sourcePreset.count()) errors.push('Expanded local material presets missing')
else {
  await sourcePreset.click()
  const fabricAfter = await page.locator('.clo-object-row').count()
  if (fabricAfter !== fabricBefore + 1) errors.push('Adding a material preset did not create exactly one swatch')
  if (!(await page.locator('.clo-object-tabs button[title="Fabric"]').getAttribute('aria-selected') === 'true')) errors.push('New material swatch did not open the Fabric browser')
}
await page.screenshot({ path: 'qa-sidebar-reference-pass-20261013.png' })
console.log(JSON.stringify({ menus, originalTabs, libraryTiles, allToolCount, errors, screenshot: 'qa-clo-ui-pass-20261013.png' }))
await browser.close()
if (errors.length) process.exit(1)
