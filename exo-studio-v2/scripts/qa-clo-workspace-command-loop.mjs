import assert from 'node:assert/strict'
import { chromium } from '../../music-empire-game/node_modules/playwright-core/index.mjs'
import { CLO_MENUS } from '../src/core/cloMenus.js'
import { indexWorkspaceCommands, searchWorkspaceCommands } from '../src/core/workspaceCommandIndex.js'
import { normalizeWorkspaceProfile } from '../src/core/workspaceProfiles.js'

// Static contracts: command search cannot silently advertise planned tools;
// workspace profiles preserve the new view arrangement and clamp bad sizes.
const catalog = indexWorkspaceCommands(CLO_MENUS)
assert(catalog.length >= 35)
assert(catalog.every(c => typeof c.action === 'string' && c.action))
assert(searchWorkspaceCommands(catalog, 'max 2d').some(c => c.action === 'workspace.view.2d'))
assert(searchWorkspaceCommands(catalog, 'animation').length === 0)
assert.equal(normalizeWorkspaceProfile({ viewportLayout: '3d', viewportSplit: 91 }).viewportSplit, 80)
assert.equal(normalizeWorkspaceProfile({ viewportLayout: 'invalid', viewportSplit: -3 }).viewportLayout, 'split')

const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=metal'] })
const context = await browser.newContext({ viewport: { width: 1520, height: 920 }, deviceScaleFactor: 1 })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })

try {
  await page.goto('http://127.0.0.1:5188/?desktop=1&testSession=tee', { waitUntil: 'domcontentloaded' })
  const windowModes = page.getByLabel('3D and 2D window arrangement')
  await windowModes.waitFor({ timeout: 15000 })
  await page.waitForTimeout(900)
  const workspaces = page.locator('.workspaces')
  const threeD = page.locator('.workspaces > .viewport-shell')
  const twoD = page.locator('.workspaces > .pattern-editor-shell')
  assert.equal(await workspaces.getAttribute('data-viewport-layout'), 'split')
  assert(await threeD.isVisible() && await twoD.isVisible())

  // These controls must not touch user garment geometry or undo history.
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem('garment-studio-tee-first-fit-project-v2')))
  const beforeRevision = before.revision
  const originalCanvasWidth = await workspaces.evaluate(el => el.getBoundingClientRect().width)
  const libraryToggle = page.getByRole('button', { name: 'Toggle asset browser panel' })
  const inspectorToggle = page.getByRole('button', { name: 'Show or hide Property Editor' })
  await libraryToggle.click()
  assert.equal(await page.locator('.main-layout').getAttribute('data-library-visible'), 'false')
  assert(!(await page.locator('.asset-browser').isVisible()))
  const withoutLibrary = await workspaces.evaluate(el => el.getBoundingClientRect().width)
  assert(withoutLibrary > originalCanvasWidth + 130, 'Collapsing Library did not release workspace width')
  await inspectorToggle.click()
  assert.equal(await page.locator('.main-layout').getAttribute('data-inspector-visible'), 'false')
  assert(!(await page.locator('.clo-inspector').isVisible()))
  const bothCollapsed = await workspaces.evaluate(el => el.getBoundingClientRect().width)
  assert(bothCollapsed > withoutLibrary + 260, 'Collapsing Property Editor did not release workspace width')
  assert(await page.locator('.tool-rail').isVisible(), 'Pattern tools disappeared on panel collapse')
  await inspectorToggle.click()
  await libraryToggle.click()
  assert.equal(await page.locator('.main-layout').getAttribute('data-library-visible'), 'true')
  assert.equal(await page.locator('.main-layout').getAttribute('data-inspector-visible'), 'true')

  await windowModes.selectOption('stack')
  assert.equal(await workspaces.getAttribute('data-viewport-layout'), 'stack')
  const topWindow = await threeD.boundingBox()
  const bottomWindow = await twoD.boundingBox()
  assert(topWindow && bottomWindow && bottomWindow.y > topWindow.y + topWindow.height - 2, 'Vertical 3D/2D stacking did not put the pattern underneath')
  const rowHandle = page.getByRole('separator', { name: 'Resize 3D and 2D windows' })
  assert.equal(await rowHandle.getAttribute('aria-orientation'), 'horizontal')
  const rowBounds = await rowHandle.boundingBox()
  await page.mouse.move(rowBounds.x + Math.min(120,rowBounds.width / 3), rowBounds.y + rowBounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(rowBounds.x + Math.min(120,rowBounds.width / 3), rowBounds.y + rowBounds.height / 2 + 60, { steps: 6 })
  await page.mouse.up()
  const tallerWindow = await threeD.boundingBox()
  assert(tallerWindow.height > topWindow.height + 35, 'Vertical layout drag failed to resize 3D height')
  const stackedValue = Number(await rowHandle.getAttribute('aria-valuenow'))
  await rowHandle.focus()
  await page.keyboard.press('ArrowUp')
  assert.equal(Number(await rowHandle.getAttribute('aria-valuenow')), stackedValue - 5)
  await windowModes.selectOption('split')
  await windowModes.selectOption('2d')
  assert(await twoD.isVisible() && !(await threeD.isVisible()), '2D maximize did not hide 3D window')
  await windowModes.selectOption('3d')
  assert(await threeD.isVisible() && !(await twoD.isVisible()), '3D maximize did not hide 2D window')
  await windowModes.selectOption('split')
  assert(await threeD.isVisible() && await twoD.isVisible())

  // Dragging the separator must actually change the editable window widths.
  const handle = page.getByRole('separator', { name: 'Resize 3D and 2D windows' })
  const firstWidth = await threeD.evaluate(el => el.getBoundingClientRect().width)
  const bounds = await handle.boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + Math.min(260, bounds.height / 3))
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 80, bounds.y + Math.min(260, bounds.height / 3), { steps: 8 })
  await page.mouse.up()
  const secondWidth = await threeD.evaluate(el => el.getBoundingClientRect().width)
  assert(secondWidth > firstWidth + 35, `3D window width did not resize (${firstWidth} -> ${secondWidth})`)
  const draggedSplit = Number(await handle.getAttribute('aria-valuenow'))
  assert(draggedSplit >= 54 && draggedSplit <= 80)
  await handle.focus()
  await page.keyboard.press('ArrowLeft')
  assert.equal(Number(await handle.getAttribute('aria-valuenow')), draggedSplit - 5)
  await handle.dblclick()
  assert.equal(await handle.getAttribute('aria-valuenow'), '50')

  // Workspace presets must retain window layout in a saved *workspace*
  // record, never write a pattern point or alter the garment's saved key.
  await windowModes.selectOption('2d')
  const presets = page.getByLabel('CLO-style workspace layout presets')
  await presets.selectOption('save')
  const savedProfile = await page.evaluate(() => JSON.parse(localStorage.getItem('garment-studio-workspace-profile-v1')))
  assert.equal(savedProfile.viewportLayout, '2d')
  await presets.selectOption('render')
  assert.equal(await workspaces.getAttribute('data-viewport-layout'), '3d')
  await presets.selectOption('restore')
  assert.equal(await workspaces.getAttribute('data-viewport-layout'), '2d')

  // The palette is not a decoration: it indexes real actions and dispatches
  // the same menu handlers while excluding unimplemented CLO tools.
  await page.keyboard.press('Meta+k')
  const dialog = page.getByRole('dialog', { name: 'Find Garment Studio commands' })
  await dialog.waitFor()
  const search = dialog.getByRole('combobox', { name: 'Search working tools and workspace commands' })
  await search.fill('show both windows')
  // Wordwise search intentionally keeps the command taxonomy predictable.
  await search.fill('show both 3d')
  await dialog.getByRole('option', { name: /show both 3d and 2d windows/i }).click()
  assert.equal(await workspaces.getAttribute('data-viewport-layout'), 'split')
  await page.keyboard.press('Meta+k')
  await search.fill('segment free sewing')
  await page.keyboard.press('Enter')
  assert((await page.locator('.pattern-canvas').getAttribute('class')).includes('tool-sew'), 'Palette sewing command did not select sewing tool')
  assert.equal(await dialog.count(), 0)
  await page.keyboard.press('Meta+k')
  await search.fill('manual cloth pin')
  await page.keyboard.press('Enter')
  assert((await page.locator('.pattern-canvas').getAttribute('class')).includes('tool-pin'), 'Pinning tool is missing from command search')
  await page.keyboard.press('Meta+k')
  await search.fill('tape measure')
  await page.keyboard.press('Enter')
  assert((await page.locator('.pattern-canvas').getAttribute('class')).includes('tool-measure'), 'Measurement tool is missing from command search')
  await page.keyboard.press('Meta+k')
  await search.fill('animation workspace')
  assert(await dialog.getByText('No working command matches that search.').isVisible(), 'Planned action appeared as available')
  await page.keyboard.press('Escape')
  assert.equal(await dialog.count(), 0)

  await page.screenshot({ path: 'qa-clo-workspace-functional-20261015.png', fullPage: false })
  await page.waitForTimeout(700)
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('garment-studio-tee-first-fit-project-v2')))
  assert.equal(after.revision, beforeRevision, 'Workspace controls changed garment revision')
  assert.deepEqual(after.pieces, before.pieces, 'Workspace controls modified garment patterns')
  assert.deepEqual(after.seams, before.seams, 'Workspace controls modified garment sewing')
  assert.deepEqual(after.fabrics, before.fabrics, 'Workspace controls modified garment fabrics')
  assert.equal(errors.length, 0, `Browser errors: ${errors.join('; ')}`)
  console.log(JSON.stringify({ pass: true, commandCount: catalog.length, baseView: 'split', horizontalAndVerticalWindowLayouts: true, resizedWidthPx: Math.round(secondWidth - firstWidth), resizedHeightPx: Math.round(tallerWindow.height - topWindow.height), freedLibraryWidthPx: Math.round(withoutLibrary - originalCanvasWidth), freedInspectorWidthPx: Math.round(bothCollapsed - withoutLibrary), draggedSplit, savedProfile: '2d', renderedProfile: '3d', restoredProfile: '2d', paletteSewingPinMeasureExecuted: true, plannedToolsHidden: true, savedGarmentUnchanged: true, browserErrors: 0, screenshot: 'qa-clo-workspace-functional-20261015.png' }, null, 2))
} finally {
  await browser.close()
}
