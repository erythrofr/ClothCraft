"""Inspect every frame of a PPF garment against itself and Blender's avatar.

Usage (run under Blender's bundled Python):
  blender --background solved.blend --python check_ppf_dynamic_contact.py -- \
    --payload tuned.json --pc2 permanent-cache.pc2 --report contact.json

This checks *surface crossings* via triangle BVHs, not just the initial
staging geometry. Cloth contact (nearby, but not intersecting) is allowed.
"""

import argparse
from collections import Counter
import json
import math
from pathlib import Path
import struct
import sys

import bpy
import numpy as np
from mathutils import Vector
from mathutils.bvhtree import BVHTree


def solver_to_blender(p):
    return Vector((p[0], -p[2], p[1]))


def parse_args():
    raw = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument('--payload', required=True)
    parser.add_argument('--pc2')
    parser.add_argument('--initial-only', action='store_true')
    parser.add_argument('--report', required=True)
    return parser.parse_args(raw)


def read_frames(path, vertex_count):
    blob = Path(path).read_bytes()
    if len(blob) < 32:
        raise RuntimeError('PPF PC2 too short')
    magic, version, count, start, rate, samples = struct.unpack_from('<12sIIffI', blob, 0)
    if not magic.startswith(b'POINTCACHE2') or version != 1 or count != vertex_count:
        raise RuntimeError('Unexpected PPF cache format or vertex count')
    if samples < 2 or len(blob) < 32 + samples * count * 12:
        raise RuntimeError('Incomplete PC2 animation')
    for frame in range(samples):
        offset = 32 + frame * count * 12
        coords = struct.unpack_from(f'<{count * 3}f', blob, offset)
        if not all(math.isfinite(v) for v in coords):
            raise RuntimeError(f'Non-finite PPF coordinates at frame {frame}')
        # IMPORTANT: the Garment Studio *payload* is in solver XYZ coordinates,
        # but the PC2 animation is generated by Blender's add-on and is
        # ALREADY in Blender coordinates (X horizontal, Y depth, Z height).
        # Reapplying the solver->Blender transform would silently invalidate
        # every cloth/avatar collision measurement.
        yield frame, [Vector((coords[i], coords[i+1], coords[i+2])) for i in range(0, len(coords), 3)]


def tree_for_object(obj):
    vertices = [obj.matrix_world @ vertex.co for vertex in obj.data.vertices]
    faces = [tuple(poly.vertices) for poly in obj.data.polygons]
    return BVHTree.FromPolygons(vertices, faces, all_triangles=False)


def main():
    args = parse_args()
    payload = json.loads(Path(args.payload).read_text())
    faces = [tuple(face) for face in payload['shell']['faces']]
    piece_ids = payload['shell'].get('facePieceIds') or ['unknown'] * len(faces)
    vertex_count = len(payload['shell']['vertices'])
    face_sets = [set(face) for face in faces]
    avatar = [obj for obj in bpy.data.objects if obj.name.startswith('PPF_Avatar_') and obj.type == 'MESH']
    if not avatar:
        raise RuntimeError('No PPF avatar collision meshes in the supplied solved Blender scene')
    avatar_bvhs = {obj.name: tree_for_object(obj) for obj in avatar}
    # Measure the largest principal stretch of each triangle, not just its
    # edge lengths. Shear can violate a strain limit without a long edge.
    rest = np.asarray([solver_to_blender(v) for v in payload['shell']['vertices']], dtype=float)
    triangles = np.asarray(faces, dtype=int)
    r1 = rest[triangles[:, 1]] - rest[triangles[:, 0]]
    r2 = rest[triangles[:, 2]] - rest[triangles[:, 0]]
    length = np.linalg.norm(r1, axis=1)
    x = np.einsum('ij,ij->i', r1, r2) / length
    y = np.linalg.norm(np.cross(r1, r2), axis=1) / length
    if np.any(length <= 1e-10) or np.any(y <= 1e-10):
        raise RuntimeError('Degenerate rest triangles cannot be strain-validated')
    inverse_rest = np.zeros((len(faces), 2, 2))
    inverse_rest[:, 0, 0] = 1 / length
    inverse_rest[:, 0, 1] = -x / (length * y)
    inverse_rest[:, 1, 1] = 1 / y
    limits = {key: float(value.get('material', {}).get('strainLimitPercent', 5)) / 100
              for key, value in payload.get('fabrics', {}).items()}
    piece_fabric = {p['id']: p.get('fabricId') for p in payload['shell'].get('pieces', [])}
    face_limits = np.array([limits.get(piece_fabric.get(pid), .05) for pid in piece_ids])
    previous_positions = None
    report = []
    avatar_part_totals = Counter()
    first_avatar_crossing = None
    first_self_crossing = None

    if args.initial_only:
        # The source payload is solver XYZ and must be converted to Blender
        # coordinates when testing pre-simulation clearance.
        initial = [solver_to_blender(v) for v in payload['shell']['vertices']]
        frame_iter = [(0, initial)]
    else:
        if not args.pc2:
            raise RuntimeError('--pc2 required for simulated-frame contact audit')
        frame_iter = read_frames(args.pc2, vertex_count)

    for frame, positions in frame_iter:
        cloth = BVHTree.FromPolygons(positions, faces, all_triangles=True)
        seen = set()
        face_pairs = Counter()
        for a, b in cloth.overlap(cloth):
            if a == b or face_sets[a] & face_sets[b]:
                continue
            pair = (min(a, b), max(a, b))
            if pair in seen:
                continue
            seen.add(pair)
            face_pairs[tuple(sorted((piece_ids[a], piece_ids[b])))] += 1
        avatar_hits = {}
        for name, avatar_tree in avatar_bvhs.items():
            hits = cloth.overlap(avatar_tree)
            if hits:
                avatar_hits[name] = len(set(hits))
                avatar_part_totals[name] += len(set(hits))
        if avatar_hits and first_avatar_crossing is None:
            first_avatar_crossing = frame
        if seen and first_self_crossing is None:
            first_self_crossing = frame
        current = np.asarray(positions, dtype=float)
        edges = np.stack((current[triangles[:, 1]] - current[triangles[:, 0]],
                          current[triangles[:, 2]] - current[triangles[:, 0]]), axis=2)
        stretch = np.linalg.svd(edges @ inverse_rest, compute_uv=False)[:, 0]
        movement = (np.linalg.norm(current - previous_positions, axis=1)
                    if previous_positions is not None else np.zeros(vertex_count))
        previous_positions = current
        report.append({
            'maxPrincipalStretch': float(stretch.max()),
            'strainLimitViolatingFaces': int(np.count_nonzero(stretch > 1 + face_limits + 0.001)),
            'maxFrameMovementMm': float(movement.max() * 1000),
            'meanFrameMovementMm': float(movement.mean() * 1000),
            'frame': frame,
            'clothSelfIntersectionPairs': len(seen),
            'piecePairsWithCrossings': [{'pieces': list(pair), 'count': count} for pair, count in face_pairs.most_common()],
            'avatarTriangleIntersectionPairs': sum(avatar_hits.values()),
            'avatarPartsWithCrossings': avatar_hits,
        })

    result = {
        'frames': len(report),
        'allFramesWithinStrainLimit': all(x['strainLimitViolatingFaces'] == 0 for x in report),
        'maxPrincipalStretch': max(x['maxPrincipalStretch'] for x in report),
        'finalMaxFrameMovementMm': report[-1]['maxFrameMovementMm'],
        'strainTolerance': 0.001,
        'shellVertices': vertex_count,
        'shellFaces': len(faces),
        'avatarCollisionMeshes': len(avatar),
        'allFramesSelfIntersectionFree': all(x['clothSelfIntersectionPairs'] == 0 for x in report),
        'allFramesAvatarIntersectionFree': all(x['avatarTriangleIntersectionPairs'] == 0 for x in report),
        'maxSelfIntersectionPairs': max(x['clothSelfIntersectionPairs'] for x in report),
        'maxAvatarIntersectionPairs': max(x['avatarTriangleIntersectionPairs'] for x in report),
        'firstAvatarCrossingFrame': first_avatar_crossing,
        'firstSelfCrossingFrame': first_self_crossing,
        'avatarPartsRankedByTotalCrossings': [
            {'name': name, 'crossings': count} for name, count in avatar_part_totals.most_common()
        ],
        'perFrame': report,
    }
    target = Path(args.report)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
